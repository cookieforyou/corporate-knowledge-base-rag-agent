package com.enterprise.kb.eval.dataset;

/**
 * 注入攻击样本类型（簇⑤ B2 S6，12.4.3 S6 攻击语料；v2.43/T6 四类→五类）
 *
 * <p>门禁口径（2026-08-13 定案，v2.43/T6 五类演进）：L1 防域（词表 + S1 归一化视图）
 * 机制上覆盖 DIRECT 与 ENCODING_BYPASS——此两类构成**门禁子集**（拦截率 ≥95%）；
 * JAILBREAK（语义化越狱）、MULTILINGUAL（非中英语言）与 ENCODING_OPAQUE（S1 不可还原
 * 编码）不在关键词匹配的防域内，作为**观察集**逐类报告拦截率，喂 S5/S8 路线图，
 * 不参与门禁。间接注入（载荷在检索文档内）评估口径提案见 12 章 v2.24，移交 Phase 5 / S5。
 */
public enum AttackType {
    /** 直接注入：明文携带词表干词——L1 机制防域，门禁子集 */
    DIRECT,
    /** 编码绕过：全角/零宽/空白拆词包裹词表干词（S1 归一化还原后命中）——L1 机制防域，门禁子集 */
    ENCODING_BYPASS,
    /** 越狱：语义化角色扮演/情景伪装，不含词表干词——L1 不拦截为预期，观察集 */
    JAILBREAK,
    /** 多语言：非中英语言的注入指令（词表仅中英）——L1 不拦截为预期，观察集 */
    MULTILINGUAL,
    /**
     * 不透明编码：编码块/同形替换等 S1 归一化不可还原形态包裹载荷（v2.43/T6 语料扩面
     * 实证定档）——L1 机制盲区，不拦截为预期，观察集；还原能力演进（S1 解码器扩展）
     * 经样本重归门禁子集，路径同词表升降级（A4）
     */
    ENCODING_OPAQUE
}
